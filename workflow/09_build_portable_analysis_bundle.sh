anything out of PRCC — clearing data-egress review and copying the artifact out
is done through official Duke channels. Confirm with Duke whether aggregate
CohortDiagnostics / CohortIncidence output and the Word report must clear review
before leaving the enclave."
  if [[ "$generic" == "true" ]]; then
    title="pad-amp-ed-desc — Portable Analysis Bundle (connection-agnostic)"
    intro="Descriptive analysis of emergency-department utilization after major lower
extremity amputation, against an institutional OMOP CDM v5.4 SQL Server
database. This bundle is connection-agnostic (e.g. for the VA or another
institution) — it does not assume Duke PRCC."
    auth_line="Kerberos (institutional NetID), if your site uses it — no passwords stored in any file."
    egress_line="This writes \`output/export_for_review/<timestamp>/\` with a small-cell-suppressed
archive of the Strategus outputs plus a reviewer manifest. It never moves
