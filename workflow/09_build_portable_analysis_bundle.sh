                                 # OMOP_AUTH_METHOD (sql / windows / kerberos -- see .env.example and
                                 # R/connection.R's header for which one matches your site)

# ── Every session ──
bash run_analysis_generic.sh    # NOT run_analysis.sh -- that one is Duke-PRCC-specific (conda + Kerberos)
```

This is the connection-agnostic bundle (e.g. for the VA or another
institution) — it ships with `.env.example` only, not a pre-filled `.env`,
and supports 4 authentication methods (`sql`, `windows`, `kerberos`,
`kerberos_prcc`) so it can connect to SQL Server the way YOUR site actually
authenticates, not just Duke's Kerberos setup. `run_analysis.R` will refuse
to run with a clear error listing any field still left as `CHANGE_ME`.

If you don't know which auth method your site uses, ask your DBA/data team
