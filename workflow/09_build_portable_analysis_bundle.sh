}

# ---------------------------------------------------------------------------
# Step 5 — Generate the bundle's README.md + .env
# ---------------------------------------------------------------------------
echo "[Step 5] Generating bundle README ..."
generate_bundle_readme "$BUNDLE"
echo "[Step 5] Generating bundle .env from INST_OMOP_* ..."
generate_bundle_env "$BUNDLE"

# ---------------------------------------------------------------------------
# Step 6 — Commit and push to GitLab (main branch)
# ---------------------------------------------------------------------------
echo "[Step 6] Pushing bundle to GitLab ($BUNDLE_GITLAB_REMOTE, branch: $BUNDLE_BRANCH) ..."
echo "  Checking SSH connectivity to GitLab ..."
if ! ssh -o BatchMode=yes -o ConnectTimeout=10 -o StrictHostKeyChecking=accept-new \
        "$(echo "$BUNDLE_GITLAB_REMOTE" | sed 's|git@\([^:]*\):.*|\1|')" \
        2>&1 | grep -qiE 'welcome|authenticated|gitlab'; then
  echo "  [WARN] SSH connectivity check inconclusive — proceeding anyway."
  echo "         Ensure you are on the Duke VPN; verify with: ssh -T git@gitlab.dhe.duke.edu"
  echo "         On 'REMOTE HOST IDENTIFICATION HAS CHANGED': ssh-keygen -R gitlab.dhe.duke.edu"
fi

cd "$BUNDLE"

if [[ ! -d ".git" ]]; then
  echo "  Initialising git repo in portable/$STUDY_NAME/ ..."
  git init -b "$BUNDLE_BRANCH"
  git remote add origin "$BUNDLE_GITLAB_REMOTE"
else
  if git remote get-url origin &>/dev/null; then
    git remote set-url origin "$BUNDLE_GITLAB_REMOTE"
  else
    git remote add origin "$BUNDLE_GITLAB_REMOTE"
  fi
  if ! git rev-parse --verify "$BUNDLE_BRANCH" &>/dev/null; then
    git checkout -b "$BUNDLE_BRANCH"
  else
    git checkout "$BUNDLE_BRANCH"
  fi
fi

if [[ -n "$BUNDLE_GIT_USER_NAME" && "$BUNDLE_GIT_USER_NAME" != "CHANGE_ME" ]]; then
  git config user.name  "$BUNDLE_GIT_USER_NAME"
  git config user.email "$BUNDLE_GIT_USER_EMAIL"
fi

if ! grep -qx "output/" .gitignore 2>/dev/null; then
  echo "output/" >> .gitignore
fi

git add -A
COMMIT_MSG="chore: sync analysis bundle $(date -u +%Y-%m-%dT%H:%M:%SZ)"
if git diff --cached --quiet; then
  echo "  No changes to commit — bundle is already up to date."
else
  git commit -m "$COMMIT_MSG"
  echo "  Committed: $COMMIT_MSG"
fi

# GITLAB_PUSH_OK tracks push success so the summary + exit code at the end of
# this script are accurate. A push failure (e.g. no Duke VPN) must NOT abort
# the script under `set -e` -- the zip fallback below is specifically meant to
# cover exactly this case ("GitLab unreachable"), so skipping it here would
# defeat its purpose. || true on each attempt keeps `set -e` from firing;
# both attempts' exit codes still surface via GITLAB_PUSH_OK.
GITLAB_PUSH_OK=false
if git push --force-with-lease origin "$BUNDLE_BRANCH" 2>&1; then
  echo "  [OK] Pushed to $BUNDLE_GITLAB_REMOTE ($BUNDLE_BRANCH)"
  GITLAB_PUSH_OK=true
else
  echo "  Retrying with --set-upstream (first push to new remote) ..."
  if git push --set-upstream origin "$BUNDLE_BRANCH" 2>&1; then
    echo "  [OK] Pushed (with --set-upstream) to $BUNDLE_GITLAB_REMOTE ($BUNDLE_BRANCH)"
    GITLAB_PUSH_OK=true
  else
    echo "  [WARN] GitLab push failed (see error above -- commonly: not on the Duke VPN)."
    echo "         The commit above is saved locally in portable/$STUDY_NAME/.git;"
    echo "         re-run this script once connectivity is restored to push it."
  fi
fi

cd "$REPO_ROOT"

# ---------------------------------------------------------------------------
# Step 7 — Build a connection-agnostic dated zip fallback in dist/
# For the VA or another institution, not the Duke GitLab push: the zip ships
# .env.example (CHANGE_ME placeholders) instead of a live .env, and a README
# without the Duke-specific clone/Kerberos/data-egress assumptions. Both are
# generated fresh into the git-tracked $BUNDLE working tree just for the zip,
# then removed/restored afterward so the GitLab bundle (already committed and
# pushed in step 6) is unaffected.
# ---------------------------------------------------------------------------
echo "[Step 7] Building zip fallback (connection-agnostic) ..."
STAMP=$(date +"%Y%m%d")
BASE="${STUDY_NAME}_${STAMP}"
EXISTING_COUNT=$(find "$DIST" -name "${BASE}*.zip" 2>/dev/null | wc -l | tr -d ' ')
if [[ "$EXISTING_COUNT" -eq 0 ]]; then
  ZIP_NAME="${BASE}.zip"
else
  ZIP_NAME="${BASE}_${EXISTING_COUNT}.zip"
fi
ZIP_PATH="$DIST/$ZIP_NAME"

generate_bundle_readme "$BUNDLE" true
generate_bundle_env_example "$BUNDLE"
(
  cd "$BUNDLE"
  # .env is excluded entirely (not swapped to placeholders) so no
  # institution-specific connection details can leak into a bundle meant to
  # be shared externally -- the recipient must `cp .env.example .env`.
  find . -mindepth 1 ! -path "./output*" ! -path "./.git*" ! -name ".env" | sort | zip -q "$ZIP_PATH" -@
)
( cd "$BUNDLE" && git checkout -- README.md && rm -f .env.example )

SIZE_MB=$(du -sm "$ZIP_PATH" | cut -f1)
echo ""
if [[ "$GITLAB_PUSH_OK" == "true" ]]; then
  echo "[Step 6] GitLab push : OK -- $BUNDLE_GITLAB_REMOTE (branch: $BUNDLE_BRANCH)"
else
  echo "[Step 6] GitLab push : FAILED -- commit saved locally in portable/$STUDY_NAME/.git; re-run once connectivity is restored"
fi
echo "[Step 7] Zip fallback: $ZIP_PATH (${SIZE_MB} MB) — connection-agnostic, safe to share externally"
echo ""

if [[ "$GITLAB_PUSH_OK" == "true" ]]; then
  echo "Steps 1-7 complete."
  echo ""
  echo "To deploy on Duke PRCC:"
  echo "  git clone --branch $BUNDLE_BRANCH $BUNDLE_GITLAB_REMOTE $STUDY_NAME"
  echo "  cd $STUDY_NAME && git pull origin $BUNDLE_BRANCH   # to update an existing clone"
else
  echo "Steps 1-7 completed with warnings (step 6, GitLab push, failed -- see above)."
  echo "The step-7 zip fallback above is a usable substitute in the meantime."
  exit 1
fi
