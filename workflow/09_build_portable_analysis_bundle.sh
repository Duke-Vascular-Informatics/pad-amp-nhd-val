## Pipeline (run_analysis.R)

1. **Strategus::execute()** — CohortGenerator + CohortDiagnostics +
   Characterization + CohortIncidence. Produces the cohort table, Table 2a
   incidence (CohortIncidence), and the standardized baseline characterization
   (Table S1b).
2. **run_vafi_plp()** — equal-weight VA-Frailty-Index discrimination/calibration
   via the PatientLevelPrediction package (Table 4, Fig 3) -> \`output/plp_vafi/\`.
3. **run_descriptive_ed_analysis()** — retained custom step: curated Table 1,
   Table 2b ED-visit diagnoses, VA-FI per-deficit odds ratios + forest plot, and
   CPT4/ICD-10-CM crosswalks -> \`output/descriptive/\`.
4. **generate_manuscript_report()** — reconfigures the module + custom outputs
   into \`output/pad-amp-ed-desc_report_<date>.docx\`.

Results are written under \`output/\` (gitignored). Kerberos tickets expire after
~10 hours; re-run \`kinit\` on authentication errors.

---

## Reproducibility

This analysis is **deterministic**: given the same CDM data snapshot and the same
OMOP vocabulary version, it reproduces exactly — run to run and site to site.
Verified by repeated clean runs producing byte-identical module outputs
(CohortIncidence incidence tables and the PatientLevelPrediction evaluation
statistics, including the AUROC confidence bounds).

- **No random number generation anywhere.** The VA-FI is applied as a fixed
  equal-weight existing model (no model fitting), there is no train/test split,
  and discrimination CIs use DeLong's analytic method (not bootstrap). No
  \`set.seed()\` is required.
- **Cohorts are generated fresh each run** (Strategus/CohortGenerator drops and
  recreates the cohort table), so a clean \`git clone\` → \`bash run_analysis.sh\`
  is fully reproducible. Do not hand-reuse a stale cohort table between runs.
- **The two inputs that govern results are the CDM data snapshot and the OMOP
  vocabulary version.** Concept sets expand through \`concept_ancestor\`, so a
  vocabulary update can change cohort membership. Both values are recorded in
  the report's Supplemental Table S1a (from \`cdm_source\`); pin/record them
  alongside any released result so the run can be reproduced.
- Cohort-definition SQL is standard OHDSI Circe output; the only tie-prone
  \`ORDER BY\` clauses order by event start date, and incidence is counted by
  date window, so tie-breaking cannot move a patient across a window boundary.

